using Cicek.SharedKernel.Domain;
using Cicek.SharedKernel.Monetary;

namespace Cicek.Domain.Ordering;

/// <summary>
/// The customer-level purchase that groups one order per shop. The (customer, idempotency key) pair is unique,
/// so a repeated submission returns the original checkout instead of creating duplicate orders. A future
/// payment covers the whole checkout.
/// </summary>
public sealed class Checkout : Entity
{
    public const int IdempotencyKeyMaxLength = 64;

    private Checkout(Guid id, Guid customerId, string idempotencyKey, Money total, DateTimeOffset now)
        : base(id)
    {
        CustomerId = customerId;
        IdempotencyKey = idempotencyKey;
        CurrencyCode = total.Currency.Code;
        TotalAmount = total.Amount;
        CreatedAt = now;
    }

    private Checkout()
    {
    }

    public Guid CustomerId { get; private set; }

    public string IdempotencyKey { get; private set; } = string.Empty;

    public string CurrencyCode { get; private set; } = string.Empty;

    public decimal TotalAmount { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public static Checkout Start(Guid customerId, string idempotencyKey, Money total, DateTimeOffset now)
    {
        if (!IsValidIdempotencyKey(idempotencyKey))
        {
            throw new DomainException("checkout.invalid_idempotency_key", "Idempotency key is invalid.");
        }

        return new Checkout(Guid.CreateVersion7(), customerId, idempotencyKey, total, now);
    }

    /// <summary>8–64 characters of [A-Za-z0-9-_] (e.g. a UUID generated by the client per submission).</summary>
    public static bool IsValidIdempotencyKey(string? key) =>
        key is { Length: >= 8 and <= IdempotencyKeyMaxLength } && key.All(c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_');
}
